const dictionaries: Record<Language, Record<string, string>> = { en, bn, zh };

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  const template = dictionaries[language][key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

function readLanguage(): Language {
  try {
    const value = window.localStorage.getItem(LANGUAGE_KEY);
    if (value === "en" || value === "bn" || value === "zh") return value;
  } catch {
    // Ignore unavailable storage.
  }
  return "en";
}

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
  language: "en",
  setLanguage: () => undefined,
  t: (key) => key,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const initial = readLanguage();
    setFormatLanguage(initial);
    return initial;
  });

  const setLanguage = useCallback((next: Language) => {
    // Formatting helpers read a module-level locale, so update it before React
    // re-renders with the new language to avoid one frame of stale locales.
    setFormatLanguage(next);
    setLanguageState(next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "bn" ? "bn" : language === "zh" ? "zh-CN" : "en";
    try {
      window.localStorage.setItem(LANGUAGE_KEY, language);
    } catch {
      // Ignore unavailable storage.
    }
  }, [language]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key, vars) => translate(language, key, vars),
    }),
    [language, setLanguage]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}
